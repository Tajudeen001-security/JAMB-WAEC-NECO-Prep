/// Returns questions matching the requested subject (and optionally type).
List<Question> getSampleQuestionsFor(String subject, {String? type, int count = 20}) {
  var all = getAllSampleQuestions();
  var filtered = all.where((q) => q.subject == subject).toList();
  if (filtered.isEmpty) {
    // fallback to any subject if no exact match
    filtered = all;
  }
  if (type != null && type.isNotEmpty) {
    final typed = filtered.where((q) => q.examType == type).toList();
    if (typed.isNotEmpty) filtered = typed;
  }
  filtered.shuffle();
  return filtered.take(count.clamp(1, filtered.length)).toList();
}
